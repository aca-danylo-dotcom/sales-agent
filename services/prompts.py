"""Шаблоны промптов для LLM: объяснение проблемы и черновик сообщения.

Все факты собирает backend (см. services/recommendation.collect_facts) — LLM
ничего не решает и не считает, только формулирует текст на украинском.
"""
from __future__ import annotations

EXPLAIN_INSTRUCTIONS = """\
Ти — асистент керівника відділу продажів. Система контролю воронки вже САМА
знайшла проблему по угоді за жорсткими правилами. Твоє завдання — коротко
пояснити менеджеру, чому це важливо саме зараз.

ПРАВИЛА:
- Пиши українською, 2-3 речення, без списків і заголовків.
- Спирайся ТІЛЬКИ на надані факти. Нічого не вигадуй: ні дат, ні сум, ні
  домовленостей, ні історії листування, яких немає у фактах.
- Не пропонуй дію і не пиши текст листа — це роблять інші частини системи.
- Не звертайся до клієнта, звертайся до менеджера. Без вітань і підписів.
- Тон діловий і спокійний, без драматизації та без емодзі.
- Не використовуй символи розмітки (*, _, #, `).
"""

DRAFT_INSTRUCTIONS = """\
Ти — досвідчений менеджер з продажу. Напиши чернетку повідомлення клієнту, щоб
зрушити угоду з місця. Повідомлення надішле менеджер вручну — ти лише готуєш
текст.

ПРАВИЛА:
- Пиши українською, від імені менеджера, звертання на «ви».
- Обсяг — 3-5 коротких абзаців, разом до 600 символів.
- Спирайся ТІЛЬКИ на надані факти. Не вигадуй домовленостей, цін, дедлайнів,
  імен і подробиць, яких немає у фактах. Якщо якогось факту немає — просто
  не згадуй його.
- Якщо ім'я контакту невідоме — почни без персонального звертання
  («Доброго дня!»), не вигадуй ім'я.
- Не тисни на клієнта, не звинувачуй його в мовчанні, не давай знижок і
  обіцянок від імені компанії.
- Заверши одним конкретним питанням або пропозицією наступного кроку.
- Тільки чистий текст повідомлення: без теми листа, без коментарів,
  без символів розмітки (*, _, #, `) і без емодзі.
"""


def _fact_lines(facts: dict) -> list[str]:
    """Только заполненные факты — пустые поля не показываем модели вовсе."""
    order = [
        ("client", "Клієнт"),
        ("contact_name", "Контактна особа"),
        ("deal_title", "Угода"),
        ("stage", "Поточний етап воронки"),
        ("amount", "Сума угоди"),
        ("owner", "Відповідальний менеджер"),
        ("idle", "Без активності"),
        ("stage_age", "На поточному етапі"),
        ("next_contact", "Запланований наступний контакт"),
        ("open_tasks", "Відкриті задачі по угоді"),
        ("last_note", "Останній коментар менеджера"),
        ("stage_history", "Історія руху по етапах"),
        ("problem", "Що знайшли правила детекції"),
        ("action", "Рекомендована дія"),
    ]
    return [f"- {label}: {facts[key]}" for key, label in order if facts.get(key)]


def build_explain_prompt(facts: dict) -> str:
    return "ФАКТИ ПО УГОДІ:\n" + "\n".join(_fact_lines(facts)) + (
        "\n\nПоясни менеджеру, чому ця угода потребує уваги зараз."
    )


def build_draft_prompt(facts: dict) -> str:
    return "ФАКТИ ПО УГОДІ:\n" + "\n".join(_fact_lines(facts)) + (
        "\n\nНапиши чернетку повідомлення клієнту під рекомендовану дію."
    )
